/** One line per operation: what a reviewer needs to see when the API changes, small enough that two pull requests rarely touch the same line. */
interface Operation {
  readonly operationId?: string;
  readonly parameters?: readonly { readonly name: string; readonly in: string; readonly required?: boolean; readonly schema?: Schema }[];
  readonly requestBody?: { readonly content?: Readonly<Record<string, { readonly schema?: Schema }>> };
  readonly responses?: Readonly<Record<string, { readonly content?: Readonly<Record<string, { readonly schema?: Schema }>> }>>;
  readonly 'x-grimoire-policy'?: Readonly<Record<string, unknown>>;
  readonly 'x-grimoire-rate-limit'?: { readonly max: number; readonly windowSeconds: number };
  readonly 'x-grimoire-idempotent'?: boolean;
}
interface Schema {
  readonly $ref?: string;
  readonly type?: string;
  readonly format?: string;
  readonly nullable?: boolean;
  readonly enum?: readonly unknown[];
  readonly items?: Schema;
  readonly properties?: Readonly<Record<string, Schema>>;
  readonly required?: readonly string[];
  readonly additionalProperties?: Schema | boolean;
  readonly oneOf?: readonly Schema[];
  readonly anyOf?: readonly Schema[];
  readonly allOf?: readonly Schema[];
  readonly minLength?: number; readonly maxLength?: number; readonly minimum?: number; readonly maximum?: number; readonly minItems?: number; readonly maxItems?: number;
  readonly minProperties?: number;
  readonly pattern?: string; readonly exclusiveMinimum?: number | boolean; readonly exclusiveMaximum?: number | boolean;
  readonly default?: unknown;
}
interface Doc { readonly components?: { readonly schemas?: Readonly<Record<string, Schema>> }; readonly paths?: Readonly<Record<string, Readonly<Record<string, Operation>>>> }

const METHODS = ['get', 'put', 'post', 'delete', 'patch'];
/** Every operation but a public one answers these with the shared error envelope (the factory adds them), so they say nothing about one route. */
const STANDARD = new Set(['401', '403', '404', '422', '429', '503']);

export const SURFACE_HEADER = [
  '# The API surface, one line per operation. Generated by `bun run openapi:surface`; never edit by hand.',
  '# Request and response shapes are written out (fields, `?` optional, `!` closed object, enum values, bounds, default); a named schema is shown by name here and in full in its own line at the end.',
  '# METHOD path | op: operationId | policy | path: parameters | query: parameters (name, `?` optional, shape) | req: request body schema | res: status:schema (the shared error statuses are left out) | rate | idem',
].join('\n');

const bound = (a: number | undefined, b: number | undefined): string => (a === undefined && b === undefined ? '' : `(${a === undefined ? '' : String(a)}..${b === undefined ? '' : String(b)})`);

/** A compact, readable shape: fields (`?` when optional), types, enum values, bounds, nested shapes; a reference is shown by its name. */
function shape(schema: Schema): string {
  if (schema.$ref !== undefined) return schema.$ref.split('/').pop() as string;
  const nullable = schema.nullable === true ? '|null' : '';
  const union = schema.oneOf ?? schema.anyOf;
  if (union !== undefined) return `${union.map(shape).join('|')}${nullable}`;
  if (schema.allOf !== undefined) return `${schema.allOf.map(shape).join('&')}${nullable}`;
  if (schema.enum !== undefined) return `${schema.enum.map(String).join('|')}${nullable}`;
  if (schema.type === 'array') return `${schema.items === undefined ? 'any' : shape(schema.items)}[]${bound(schema.minItems, schema.maxItems)}${nullable}`;
  if (schema.type === 'object' || schema.properties !== undefined) {
    const required = new Set(schema.required ?? []);
    const fields = Object.keys(schema.properties ?? {}).sort().map((k) => `${k}${required.has(k) ? '' : '?'}:${shape((schema.properties as Record<string, Schema>)[k] as Schema)}`);
    const extra = typeof schema.additionalProperties === 'object' ? [`*:${shape(schema.additionalProperties)}`] : [];
    const strict = schema.additionalProperties === false ? '!' : '';
    return `{${[...fields, ...extra].join(',')}}${strict}${schema.minProperties === undefined ? '' : `(min properties ${String(schema.minProperties)})`}${nullable}`;
  }
  const format = schema.format === undefined ? '' : `<${schema.format}>`;
  const above = typeof schema.exclusiveMinimum === 'number' ? `>${String(schema.exclusiveMinimum)}` : '';
  const below = typeof schema.exclusiveMaximum === 'number' ? `<${String(schema.exclusiveMaximum)}` : '';
  const pattern = schema.pattern === undefined ? '' : `/${schema.pattern}/`;
  const fallback = schema.default === undefined ? '' : `=${JSON.stringify(schema.default)}`;
  return `${schema.type ?? 'any'}${format}${bound(schema.minLength ?? schema.minimum, schema.maxLength ?? schema.maximum)}${above}${below}${pattern}${nullable}${fallback}`;
}
const name = (schema: Schema | undefined): string => (schema === undefined ? '-' : shape(schema));
const jsonSchema = (content: Readonly<Record<string, { readonly schema?: Schema }>> | undefined): string => name(content?.['application/json']?.schema);

function line(method: string, route: string, op: Operation): string {
  const policy = op['x-grimoire-policy'] ?? {};
  const kind = String(policy['kind']);
  const rest = Object.keys(policy).filter((k) => k !== 'kind').sort().map((k) => String(policy[k]));
  const params = (where: string): string => {
    const list = (op.parameters ?? []).filter((p) => p.in === where).sort((a, b) => (a.name < b.name ? -1 : 1))
      .map((p) => `${p.name}${p.required === true ? '' : '?'}:${p.schema === undefined ? 'any' : shape(p.schema)}`);
    return list.length === 0 ? '-' : list.join(',');
  };
  const responses = Object.entries(op.responses ?? {})
    .filter(([status]) => !STANDARD.has(status))
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([status, r]) => `${status}:${jsonSchema(r.content)}`);
  const rate = op['x-grimoire-rate-limit'];
  return [
    `${method.toUpperCase()} ${route}`, `op:${op.operationId ?? '-'}`, `policy:${[kind, ...rest].join(':')}`, `path:${params('path')}`, `query:${params('query')}`,
    `req:${jsonSchema(op.requestBody?.content)}`, `res:${responses.join(',')}`, `rate:${rate === undefined ? '-' : `${String(rate.max)}/${String(rate.windowSeconds)}s`}`,
    `idem:${op['x-grimoire-idempotent'] === true ? 'yes' : 'no'}`,
  ].join(' | ');
}

/** The surface text of a document, sorted by path then method, with the header and a final newline. */
export function surface(document: object): string {
  const lines: string[] = [];
  for (const [route, item] of Object.entries((document as Doc).paths ?? {})) {
    for (const method of METHODS) {
      const op = item[method];
      if (op !== undefined) lines.push(line(method, route, op));
    }
  }
  const schemas = Object.entries((document as Doc).components?.schemas ?? {}).map(([n, schema]) => `schema ${n} = ${shape(schema)}`);
  const order = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);
  return `${SURFACE_HEADER}\n${[...lines.sort(order), ...schemas.sort(order)].map((l) => `${l}\n`).join('')}`;
}

/** The lines that differ, for a message a reviewer can act on: `+` is in the build and not recorded, `-` is recorded and not in the build. */
export function surfaceDiff(recorded: string, built: string): string[] {
  const a = new Set(recorded.split('\n'));
  const b = new Set(built.split('\n'));
  return [...[...b].filter((l) => !a.has(l)).map((l) => `+ ${l}`), ...[...a].filter((l) => !b.has(l)).map((l) => `- ${l}`)].filter((l) => l.length > 2);
}
